const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const cache = new Map();
function load(file) {
  const resolved = path.resolve(__dirname, '..', file);
  if (cache.has(resolved)) return cache.get(resolved);
  const module = { exports: {} }; cache.set(resolved, module.exports);
  const code = ts.transpileModule(fs.readFileSync(resolved, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
  new Function('require', 'module', 'exports', code)(name => name === './catalog' ? load('src/lib/experience/catalog.ts') : require(name), module, module.exports);
  return module.exports;
}
const { applyUpdates, nextQuestion, newDraft, readLiveDraft, appendTranscript, parseTurnOutput } = load('src/lib/experience/live-plan.ts');
const initial = newDraft();
const mapped = parseTurnOutput({ updates: { target: { answer: '어르신 30명' }, activities: { answer: '의자 마련' } }, reply: '언제 시작하나요?' });
assert.equal(mapped.updates.length, 2, 'Accept the keyed response returned by the actual provider');
assert.equal(parseTurnOutput({ updates: [{ key: 'unknown', answer: 'x' }], reply: 'x' }), null, 'Reject unknown document fields');
assert.equal(parseTurnOutput({ updates: [], reply: '' }), null, 'Reject empty assistant replies');
assert.ok(parseTurnOutput({ output: { updates: [], reply: '조금 더 알려주세요.' } }), 'Accept a wrapped structured reply');
let state = applyUpdates(initial.answers, [], [{ key: 'target', answer: '30명' }, { key: 'need', answer: '회관 노후' }]);
state = applyUpdates(state.answers, state.skipped, [{ key: 'target', answer: '20명' }]);
assert.equal(state.answers[1], '20명', 'Corrections replace old counts');
assert.equal(state.answers[0], '회관 노후', 'Corrections preserve unrelated answers');
state = applyUpdates(state.answers, [], [{ key: 'activities', answer: '', skipped: true }]);
assert.equal(nextQuestion(state.answers, state.skipped), 'participation', 'Unknown items can be deferred');
state = applyUpdates(state.answers, state.skipped, [{ key: 'activities', answer: '의자 구입' }]);
assert.ok(!state.skipped.includes('activities'), 'Answering a deferred item reopens it correctly');
assert.equal(nextQuestion(Array(8).fill('답변'), []), null, 'All answered items finish the interview');
let messages = appendTranscript([], 'user', '회관을', 0, 1000);
messages = appendTranscript(messages, 'assistant', '네', 1000, 1200);
messages = appendTranscript(messages, 'user', ' 고치고 싶어요', 1100, 2000);
assert.equal(messages.length, 2, 'Overlapping backchannels do not split user speech');
assert.equal(messages[0].text, '회관을 고치고 싶어요', 'Preserve spaces exactly');
messages = appendTranscript(messages, 'user', '다시 시작', 1500, 2000, 'another-session');
assert.equal(messages.length, 3, 'Reconnecting starts a separate transcript timeline');
assert.equal(readLiveDraft(JSON.stringify({ ...initial, answers: ['too short'] })).answers.length, 8);
assert.equal(readLiveDraft(JSON.stringify({ ...initial, expires: 1, answers: Array(8).fill('expired') })).answers[0], '', 'Expired drafts are not restored');
console.log('PASS: provider response normalization, corrections, skipped questions, completion, full-duplex captions, and draft recovery');
